// --- Helpers -------------------------------------------------------------

const day = (iso: string) => new Date(iso);

async function wipe() {
  // Reverse FK order: children first. CASCADE would also work, but this
  // keeps the call explicit and matches the SQL TRUNCATE ... CASCADE.
  await prisma.notification.deleteMany();
  await prisma.activity.deleteMany();
  await prisma.comment.deleteMany();
  await prisma.taskLabel.deleteMany();
  await prisma.task.deleteMany();
  await prisma.label.deleteMany();
  await prisma.projectMember.deleteMany();
  await prisma.project.deleteMany();
  await prisma.user.deleteMany();
}

async function seed() {
  const passwordHash = await hash(PASSWORD);

  // Users
  for (const u of USERS) {
    await prisma.user.create({
      data: {
        id: u.id,
        name: u.name,
        email: u.email,
        passwordHash,
        createdAt: day(u.createdAt),
      },
    });
  }

  // Projects
  for (const p of PROJECTS) {
    await prisma.project.create({
      data: {
        id: p.id,
        name: p.name,
        description: p.description,
        status: p.status,
        ownerId: p.owner,
        createdAt: day(p.createdAt),
        updatedAt: day(p.updatedAt),
      },
    });
  }

  // Members
  for (const m of MEMBERS) {
    await prisma.projectMember.create({
      data: {
        id: m.id,
        projectId: m.project,
        userId: m.user,
        role: m.role,
        joinedAt: day(m.joinedAt),
      },
    });
  }

  // Labels
  for (const l of LABELS) {
    await prisma.label.create({
      data: {
        id: l.id,
        projectId: l.project,
        name: l.name,
        color: l.color,
      },
    });
  }

  // Tasks
  for (const t of TASKS) {
    await prisma.task.create({
      data: {
        id: t.id,
        projectId: t.project,
        title: t.title,
        description: t.description,
        status: t.status,
        priority: t.priority,
        position: t.position,
        dueDate: t.dueDate ? day(t.dueDate) : null,
        assigneeId: t.assignee,
        creatorId: t.creator,
        completedAt: t.completedAt ? day(t.completedAt) : null,
        createdAt: day(t.createdAt),
        updatedAt: day(t.updatedAt),
      },
    });
  }

  // Task ↔ Labels
  for (const [taskId, labelId] of TASK_LABELS) {
    await prisma.taskLabel.create({
      data: { taskId, labelId },
    });
  }

  // Comments
  for (const c of COMMENTS) {
    await prisma.comment.create({
      data: {
        id: c.id,
        taskId: c.task,
        authorId: c.author,
        body: c.body,
        createdAt: day(c.createdAt),
        updatedAt: day(c.updatedAt),
      },
    });
  }

  // Activity
  for (const a of ACTIVITY) {
    await prisma.activity.create({
      data: {
        id: a.id,
        projectId: a.project,
        actorId: a.actor,
        action: a.action,
        message: a.message,
        createdAt: day(a.createdAt),
      },
    });
  }

  // Notifications
  for (const n of NOTIFICATIONS) {
    await prisma.notification.create({
      data: {
        id: n.id,
        userId: n.user,
        type: n.type,
        message: n.message,
        link: n.link,
        readAt: n.readAt ? day(n.readAt) : null,
        createdAt: day(n.createdAt),
      },
    });
  }
}

async function main() {
  console.log('🌱 Seeding TaskForge demo data…');
  console.log('   Wiping existing rows…');
  await wipe();
  console.log('   Inserting demo rows…');
  await seed();
  console.log(
    `✅ Seeded: ${USERS.length} users, ${PROJECTS.length} projects, ${MEMBERS.length} members, ` +
      `${LABELS.length} labels, ${TASKS.length} tasks, ${TASK_LABELS.length} task_labels, ` +
      `${COMMENTS.length} comments, ${ACTIVITY.length} activity, ${NOTIFICATIONS.length} notifications.`,
  );
  console.log(`\n   Login with owner@demo.dev / ${PASSWORD}`);
}

main()
  .catch((e) => {
    console.error('❌ Seed failed:', e);
    process.exit(1);
  })
  .finally(() => void prisma.$disconnect());
